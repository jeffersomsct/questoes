-- Banco de questões para concursos — PostgreSQL 14+
-- Três camadas independentes: TAXONOMIA (conteúdo) · PROVA (banca/concurso/cargo) · USO (respostas do aluno)
BEGIN;

-- ============ 1. TAXONOMIA: Área > Disciplina > Assunto > Subassunto ============
CREATE TABLE area (
  id     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo TEXT NOT NULL UNIQUE,            -- AREA-01
  nome   TEXT NOT NULL UNIQUE
);
CREATE TABLE disciplina (
  id      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  area_id INT NOT NULL REFERENCES area(id),
  codigo  TEXT NOT NULL UNIQUE,           -- DISC-03-01
  nome    TEXT NOT NULL,
  UNIQUE (area_id, nome)
);
-- Assunto e subassunto na mesma tabela (parent_id). Subassuntos são criados ao cadastrar questões.
CREATE TABLE assunto (
  id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  disciplina_id INT NOT NULL REFERENCES disciplina(id),
  parent_id     INT REFERENCES assunto(id),
  codigo        TEXT NOT NULL UNIQUE,     -- ASS-03-01-005 (subassuntos: ASS-...-005.01)
  nome          TEXT NOT NULL,
  nivel         SMALLINT NOT NULL DEFAULT 1 CHECK (nivel BETWEEN 1 AND 5)
);
-- Sem duplicação dentro da mesma disciplina/pai
CREATE UNIQUE INDEX ux_assunto_nome ON assunto (disciplina_id, COALESCE(parent_id, 0), lower(nome));
CREATE INDEX ix_assunto_parent ON assunto (parent_id);

-- Relação entre assuntos de disciplinas diferentes (ex.: Licitações ↔ Compras públicas)
-- A disciplina de origem é preservada; a relação não funde os assuntos.
CREATE TABLE assunto_relacionado (
  assunto_a INT NOT NULL REFERENCES assunto(id) ON DELETE CASCADE,
  assunto_b INT NOT NULL REFERENCES assunto(id) ON DELETE CASCADE,
  tipo      TEXT NOT NULL DEFAULT 'CORRELATO' CHECK (tipo IN ('MESMO_TEMA','CORRELATO')),
  PRIMARY KEY (assunto_a, assunto_b),
  CHECK (assunto_a < assunto_b)
);

-- ============ 2. PROVA: independente da hierarquia de conteúdo ============
CREATE TABLE banca (
  id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome TEXT NOT NULL UNIQUE
);
CREATE TABLE concurso (
  id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome     TEXT NOT NULL,                 -- Justiça Federal
  orgao    TEXT,
  ano      SMALLINT NOT NULL,
  banca_id INT REFERENCES banca(id),
  UNIQUE (nome, ano)
);
CREATE TABLE cargo (
  id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  concurso_id INT NOT NULL REFERENCES concurso(id) ON DELETE CASCADE,
  nome        TEXT NOT NULL,              -- Oficial de Justiça
  nivel       TEXT CHECK (nivel IN ('FUNDAMENTAL','MEDIO','SUPERIOR')),
  UNIQUE (concurso_id, nome)
);
-- Edital: quais assuntos cada cargo cobra (base para simulados e gráficos por cargo)
CREATE TABLE cargo_assunto (
  cargo_id   INT NOT NULL REFERENCES cargo(id) ON DELETE CASCADE,
  assunto_id INT NOT NULL REFERENCES assunto(id),
  peso       NUMERIC(5,2),
  PRIMARY KEY (cargo_id, assunto_id)
);

-- ============ 3. QUESTÕES ============
CREATE TABLE questao (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  assunto_id   INT NOT NULL REFERENCES assunto(id),   -- disciplina e área derivam daqui
  banca_id     INT REFERENCES banca(id),
  concurso_id  INT REFERENCES concurso(id),
  cargo_id     INT REFERENCES cargo(id),
  ano          SMALLINT,
  tipo         TEXT NOT NULL DEFAULT 'MULTIPLA' CHECK (tipo IN ('MULTIPLA','CERTO_ERRADO')),
  enunciado    TEXT NOT NULL,
  gabarito     TEXT NOT NULL,                         -- 'A'..'E' ou 'C'/'E'
  comentario   TEXT,
  anulada      BOOLEAN NOT NULL DEFAULT false,
  criada_em    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE alternativa (
  questao_id BIGINT NOT NULL REFERENCES questao(id) ON DELETE CASCADE,
  letra      CHAR(1) NOT NULL,
  texto      TEXT NOT NULL,
  PRIMARY KEY (questao_id, letra)
);
-- Filtros do banco de questões
CREATE INDEX ix_q_assunto  ON questao (assunto_id);
CREATE INDEX ix_q_banca    ON questao (banca_id);
CREATE INDEX ix_q_concurso ON questao (concurso_id, cargo_id);
CREATE INDEX ix_q_ano      ON questao (ano);
CREATE INDEX ix_q_busca    ON questao USING gin (to_tsvector('portuguese', enunciado));

-- ============ 4. USO DO ALUNO ============
CREATE TABLE usuario (
  id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome  TEXT NOT NULL,
  email TEXT NOT NULL UNIQUE
);
-- Modo PROVA: caderno com várias disciplinas; gabarito só liberado ao finalizar
CREATE TABLE simulado (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id    INT NOT NULL REFERENCES usuario(id),
  titulo        TEXT NOT NULL,
  cargo_id      INT REFERENCES cargo(id),
  duracao_min   INT,
  iniciado_em   TIMESTAMPTZ NOT NULL DEFAULT now(),
  finalizado_em TIMESTAMPTZ                          -- NULL = gabarito oculto
);
CREATE TABLE simulado_questao (
  simulado_id BIGINT NOT NULL REFERENCES simulado(id) ON DELETE CASCADE,
  questao_id  BIGINT NOT NULL REFERENCES questao(id),
  ordem       INT NOT NULL,
  PRIMARY KEY (simulado_id, questao_id)
);
-- Uma linha por resposta: histórico completo (vezes respondida, erros, tempo)
CREATE TABLE tentativa (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id     INT NOT NULL REFERENCES usuario(id),
  questao_id     BIGINT NOT NULL REFERENCES questao(id),
  simulado_id    BIGINT REFERENCES simulado(id),      -- NULL = modo padrão
  resposta       TEXT NOT NULL,
  acertou        BOOLEAN NOT NULL,
  tempo_segundos INT NOT NULL CHECK (tempo_segundos >= 0),
  respondida_em  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_t_usuario_questao ON tentativa (usuario_id, questao_id);
CREATE INDEX ix_t_usuario_data    ON tentativa (usuario_id, respondida_em);
-- Anotação persistente: exibida nas próximas vezes que a questão aparecer
CREATE TABLE anotacao (
  usuario_id    INT NOT NULL REFERENCES usuario(id),
  questao_id    BIGINT NOT NULL REFERENCES questao(id) ON DELETE CASCADE,
  texto         TEXT NOT NULL,
  atualizada_em TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (usuario_id, questao_id)
);

-- ============ 5. VIEWS ============
-- Resumo por usuário×questão: base para "mais errei / mais demoradas / menos respondidas"
CREATE VIEW v_desempenho_questao AS
SELECT t.usuario_id, t.questao_id,
       count(*)                                   AS vezes_respondida,
       count(*) FILTER (WHERE NOT t.acertou)      AS erros,
       round(avg(t.tempo_segundos))               AS tempo_medio_s,
       max(t.respondida_em)                       AS ultima_resposta,
       (array_agg(t.acertou ORDER BY t.respondida_em DESC))[1] AS acertou_ultima
FROM tentativa t GROUP BY t.usuario_id, t.questao_id;

-- Gráficos: aproveitamento por assunto (agrega no nível de assunto raiz)
CREATE VIEW v_desempenho_assunto AS
WITH RECURSIVE raiz AS (
  SELECT id, id AS raiz_id FROM assunto WHERE parent_id IS NULL
  UNION ALL
  SELECT a.id, r.raiz_id FROM assunto a JOIN raiz r ON a.parent_id = r.id
)
SELECT t.usuario_id, ar.id AS area_id, d.id AS disciplina_id, r.raiz_id AS assunto_id,
       count(*) AS respostas,
       count(*) FILTER (WHERE t.acertou) AS acertos,
       round(100.0 * count(*) FILTER (WHERE t.acertou) / count(*), 1) AS aproveitamento_pct,
       round(avg(t.tempo_segundos)) AS tempo_medio_s
FROM tentativa t
JOIN questao q ON q.id = t.questao_id
JOIN raiz r ON r.id = q.assunto_id
JOIN assunto a ON a.id = r.raiz_id
JOIN disciplina d ON d.id = a.disciplina_id
JOIN area ar ON ar.id = d.area_id
GROUP BY t.usuario_id, ar.id, d.id, r.raiz_id;

-- Gráficos: aproveitamento por disciplina
CREATE VIEW v_desempenho_disciplina AS
SELECT usuario_id, area_id, disciplina_id, sum(respostas) AS respostas, sum(acertos) AS acertos,
       round(100.0 * sum(acertos) / sum(respostas), 1) AS aproveitamento_pct
FROM v_desempenho_assunto GROUP BY usuario_id, area_id, disciplina_id;

COMMIT;
